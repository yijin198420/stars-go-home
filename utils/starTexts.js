// 同一类文案不连续重复，避免短时间内打破沉浸感
const lastPickedByGroup = {};

function pickDifferent(list, group) {
  if (!list || list.length === 0) return '';
  let index = Math.floor(Math.random() * list.length);
  if (list.length > 1 && index === lastPickedByGroup[group]) {
    index = (index + 1 + Math.floor(Math.random() * (list.length - 1))) % list.length;
  }
  lastPickedByGroup[group] = index;
  return list[index];
}

// 从私语里随机取一句
function getRandomWhisper() {
  return pickDifferent(whisperTexts, 'whisper');
}

// 从某个类型的文案里随机取一句。
// 传入 mood 时，有 30% 概率换成这种心情特有的句子，
// 让不同陪伴需要下的夜晚，说出不同的话。
function getRandomText(type, mood) {
  if (mood && moodLines[mood] && Math.random() < 0.3) {
    const list = moodLines[mood];
    return pickDifferent(list, 'mood-' + mood);
  }
  const list = catchTexts[type] || catchTexts.calm;
  return pickDifferent(list, 'catch-' + (type || 'calm'));
}

// 从 miss 文案里随机取一句
function getRandomMissText() {
  return pickDifferent(missTexts, 'miss');
}

