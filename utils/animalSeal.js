function M(x, y) { return ['moveTo', x, y]; }
function L(x, y) { return ['lineTo', x, y]; }
function Q(cx, cy, x, y) { return ['quadraticCurveTo', cx, cy, x, y]; }
function Z() { return ['closePath']; }
function E(cx, cy, rx, ry) {
  return [M(cx - rx, cy), Q(cx - rx, cy - ry, cx, cy - ry), Q(cx + rx, cy - ry, cx + rx, cy), Q(cx + rx, cy + ry, cx, cy + ry), Q(cx - rx, cy + ry, cx - rx, cy), Z()];
}
function S(cx, cy, outer, inner) {
  const commands = [];
  for (let i = 0; i < 10; i++) {
    const radius = i % 2 === 0 ? outer : inner;
    const angle = -Math.PI / 2 + i * Math.PI / 5;
    const point = [cx + Math.cos(angle) * radius, cy + Math.sin(angle) * radius];
    commands.push(i === 0 ? M(point[0], point[1]) : L(point[0], point[1]));
  }
  commands.push(Z());
  return commands;
}
function P(commands, tone) {
  return { commands: commands, tone: tone || 'body' };
}

