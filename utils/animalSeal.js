function hash(text) {
  return String(text || '').split('').reduce(function (value, char) {
    return (value * 31 + char.charCodeAt(0)) >>> 0;
  }, 17);
}

function getAnimalSeal(title) {
  const safeTitle = String(title || '今晚的无名星空');
  const entries = ANIMAL_ALIASES.concat(PRIMARY_ANIMALS).sort(function (a, b) { return b[0].length - a[0].length; });
  const found = entries.find(function (entry) { return safeTitle.indexOf(entry[0]) >= 0; });
  if (found) return { name: found[0], character: found[1], icon: found[2] };
  const fallback = PRIMARY_ANIMALS[hash(safeTitle) % PRIMARY_ANIMALS.length];
  return { name: fallback[0], character: fallback[1], icon: fallback[2] };
}

function drawCommandPath(ctx, commands, fillColor, skipStroke, fillOpen) {
  ctx.beginPath();
  let closed = false;
  commands.forEach(function (command) {
    const method = command[0];
    if (method === 'closePath') closed = true;
    if (typeof ctx[method] === 'function') ctx[method].apply(ctx, command.slice(1));
  });
  // 最终烟花角色允许闭合身体承接一层很薄的水粉色。小星印不传
  // fillColor，仍然保持原来的单色简笔画，避免 24px 图标糊成色块。
  if ((closed || fillOpen) && fillColor && typeof ctx.fill === 'function') {
    ctx.save();
    ctx.fillStyle = fillColor;
    ctx.fill();
    ctx.restore();
  }
  if (!skipStroke) ctx.stroke();
}

function drawAnimalDoodle(ctx, icon, cx, cy, size, color, options) {
  if (!ctx) return;
  options = options || {};
  const doodle = options.storyPose
    ? (STORY_CHARACTERS[icon] || STORY_CHARACTERS.bear)
    : (AVATARS[icon] || AVATARS.bear);
  const scale = (size || 24) / 32;
  const widthScale = options.widthScale || 1;
  const heightScale = options.heightScale || 1;
  const stroke = color || 'rgba(244,232,201,.88)';
  ctx.save();
  ctx.translate(cx, cy);
  if (options.rotation && typeof ctx.rotate === 'function') ctx.rotate(options.rotation);
  ctx.scale(scale * widthScale, scale * heightScale);
  ctx.translate(-16, -16);
  ctx.strokeStyle = stroke;
  ctx.fillStyle = stroke;
  ctx.lineWidth = options.lineWidth || 1.42;
  ctx.lineCap = 'round';
  ctx.lineJoin = 'round';
  if (options.paintOnly) {
    const paintShapes = STORY_PAINT_SHAPES[icon] || STORY_PAINT_SHAPES.bear;
    paintShapes.forEach(function (shape) {
      const commands = shape.commands || shape;
      const tone = shape.tone || 'body';
      const paintColor = tone === 'accent'
        ? (options.accentFillColor || options.secondaryFillColor || options.fillColor || stroke)
        : (tone === 'shadow'
          ? (options.secondaryFillColor || options.fillColor || stroke)
          : (options.fillColor || stroke));
      drawCommandPath(ctx, commands, paintColor, true, false);
    });
    ctx.restore();
    return;
  }
  if (options.dashed && typeof ctx.setLineDash === 'function') ctx.setLineDash([1.65, 0.88]);
  if (!options.skipOutline) {
    doodle.outline.forEach(function (commands) { drawCommandPath(ctx, commands, options.fillColor, options.paintOnly, options.fillOpen); });
  }
  if (typeof ctx.setLineDash === 'function') ctx.setLineDash([]);
  ctx.strokeStyle = options.accentColor || stroke;
  ctx.lineWidth = (options.lineWidth || 1.42) * 0.82;
  if (!options.skipAccent) {
    doodle.accent.forEach(function (commands) { drawCommandPath(ctx, commands, options.accentFillColor); });
  }
  if (options.storyPose && !options.skipProp) {
    ctx.strokeStyle = options.propColor || options.accentColor || stroke;
    ctx.fillStyle = options.propColor || options.accentColor || stroke;
    ctx.lineWidth = (options.lineWidth || 1.42) * 0.88;
    (STORY_PROPS[icon] || []).forEach(function (commands) {
      drawCommandPath(ctx, commands, options.propFillColor);
    });
  }
  ctx.strokeStyle = options.faceColor || stroke;
  ctx.fillStyle = options.faceColor || stroke;
  ctx.lineWidth = (options.lineWidth || 1.42) * 0.92;
  if (!options.skipFace) doodle.face.forEach(function (commands) { drawCommandPath(ctx, commands); });
  if (!options.skipDots) {
    doodle.dots.forEach(function (dot) {
      ctx.beginPath();
      ctx.arc(dot[0], dot[1], dot[2] || 0.8, 0, Math.PI * 2);
      ctx.fill();
    });
  }
  if (options.cheeks) {
    const cheeks = doodle.cheeks || CHEEKS[icon] || CHEEKS.bear;
    ctx.fillStyle = options.cheekColor || 'rgba(255,155,164,.9)';
    cheeks.forEach(function (cheek) {
      ctx.beginPath();
      ctx.arc(cheek[0], cheek[1], options.cheekRadius || 1.18, 0, Math.PI * 2);
      ctx.fill();
    });
  }
  ctx.restore();
}

function sampleSegment(points, start, end, steps) {
  for (let i = 1; i <= steps; i++) {
    const p = i / steps;
    points.push({ x: start.x + (end.x - start.x) * p, y: start.y + (end.y - start.y) * p });
  }
}

function sampleAnimalDoodle(icon, options) {
  options = options || {};
  const doodle = options.storyPose
    ? (STORY_CHARACTERS[icon] || STORY_CHARACTERS.bear)
    : (AVATARS[icon] || AVATARS.bear);
  const points = [];
  const widthScale = options.widthScale || 1;
  const heightScale = options.heightScale || 1;
  function styledPoint(point) {
    return {
      x: 16 + (point.x - 16) * widthScale,
      y: 16 + (point.y - 16) * heightScale,
      tone: point.tone,
      pathIndex: point.pathIndex
    };
  }
  function samplePaths(paths, tone) {
    paths.forEach(function (commands, pathIndex) {
    let cursor = { x: 0, y: 0 };
    let beginning = null;
    commands.forEach(function (command) {
      if (command[0] === 'moveTo') {
        cursor = { x: command[1], y: command[2] };
        beginning = { x: cursor.x, y: cursor.y };
        points.push({ x: cursor.x, y: cursor.y, tone: tone, pathIndex: pathIndex });
      } else if (command[0] === 'lineTo') {
        const end = { x: command[1], y: command[2] };
        const before = points.length;
        sampleSegment(points, cursor, end, 4);
        for (let i = before; i < points.length; i++) {
          points[i].tone = tone;
          points[i].pathIndex = pathIndex;
        }
        cursor = end;
      } else if (command[0] === 'quadraticCurveTo') {
        const start = { x: cursor.x, y: cursor.y };
        const control = { x: command[1], y: command[2] };
        const end = { x: command[3], y: command[4] };
        for (let step = 1; step <= 8; step++) {
          const p = step / 8;
          const inv = 1 - p;
          points.push({
            x: inv * inv * start.x + 2 * inv * p * control.x + p * p * end.x,
            y: inv * inv * start.y + 2 * inv * p * control.y + p * p * end.y,
            tone: tone,
            pathIndex: pathIndex
          });
        }
        cursor = end;
      } else if (command[0] === 'closePath' && beginning) {
        const before = points.length;
        sampleSegment(points, cursor, beginning, 4);
        for (let i = before; i < points.length; i++) {
          points[i].tone = tone;
          points[i].pathIndex = pathIndex;
        }
        cursor = beginning;
      }
    });
  });
  }
  samplePaths(doodle.outline, 'outline');
  samplePaths(doodle.accent, 'accent');
  if (options.storyPose) samplePaths(STORY_PROPS[icon] || [], 'prop');
  samplePaths(doodle.face, 'face');
  doodle.dots.forEach(function (dot) {
    for (let i = 0; i < 5; i++) {
      const angle = i / 5 * Math.PI * 2;
      points.push({ x: dot[0] + Math.cos(angle) * dot[2], y: dot[1] + Math.sin(angle) * dot[2], tone: 'face' });
    }
  });
  (doodle.cheeks || []).forEach(function (cheek) {
    for (let i = 0; i < 8; i++) {
      const angle = i / 8 * Math.PI * 2;
      points.push({ x: cheek[0] + Math.cos(angle) * 1.18, y: cheek[1] + Math.sin(angle) * 1.18, tone: 'cheek' });
    }
  });
  return points.map(styledPoint);
}

